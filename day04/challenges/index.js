function checkEvenOdd(number) {
    if (number % 2 === 0) {
        console.log("Even");
    } else {
        console.log("Odd");
    }
}

checkEvenOdd(8);
checkEvenOdd(17);
checkEvenOdd(24);
checkEvenOdd(31);
